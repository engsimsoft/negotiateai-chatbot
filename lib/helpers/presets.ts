// Map для быстрого доступа по ID
export const PRESET_HELPERS_MAP = new Map<string, PresetHelper>(
  PRESET_HELPERS.map((h) => [h.id, h])
);

/**
 * Получить preset помощника по ID
 */
export function getPresetHelperById(id: string): PresetHelper | null {
  return PRESET_HELPERS_MAP.get(id) || null;
}

/**
 * Проверить, является ли ID preset помощником
 */
export function isPresetHelperId(id: string): boolean {
  return PRESET_HELPERS_MAP.has(id);
}
