import "server-only";

/**
 * System prompt для compaction:summarize. Фиксированный текст — не меняется
 * от вызова к вызову.
 *
 * Target размер summary: `COMPACTION_SUMMARY_TARGET_TOKENS` = 3000 токенов
 * (hard cap 4096 задан через `DEFAULT_MAX_OUTPUT_TOKENS["compaction:summarize"]`).
 */
export const COMPACTION_SUMMARY_SYSTEM_PROMPT = `Ты — помощник сжатия контекста длинных разговоров. Твоя задача — создать структурированный итог (summary) старой части разговора, чтобы освободить контекстное окно для продолжения беседы.

## Что нужно сделать

Проанализируй предоставленный разговор и извлеки ключевую информацию в 5 секций:

1. **Контекст задачи** — что пользователь решает, над чем работает, какие цели.
2. **Загруженные материалы** — какие документы/файлы предоставлены и ключевые данные из каждого (не метаданные, а содержимое).
3. **Ключевые решения и выводы** — что решили, какие ограничения установлены, важные факты, договорённости.
4. **Текущий фокус** — на чём остановились, что обсуждается прямо сейчас.
5. **Открытые вопросы** — что ещё не решено, что пользователь планирует обсудить.

## Требования

- Сжимай фактологически, не стилистически — пересказ важнее оригинального стиля.
- Для материалов из вложений фиксируй конкретные данные и выводы, а не имена файлов.
- Не дублируй то что уже есть в системном промпте.
- Целевой объём summary — около 3000 токенов суммарно. Если разговор короче и фактов мало — пиши короче.
- **Язык итога:** пиши на том же языке, что использует пользователь в разговоре. Если разговор смешанный — выбирай преобладающий язык.

## Формат ответа

Ответ — строго JSON-объект с 5 полями, по одному текстовому блоку на секцию. Каждое поле — markdown-строка без заголовков секций (заголовки добавит caller).`;

/**
 * Builds the user prompt for a compaction call. Composes the conversation
 * block with optional previous summary (rolling update pattern).
 *
 * Rolling update: при повторных сжатиях (Фаза 2) модель получает
 * предыдущий summary и инструкцию «обнови его новыми данными», а не
 * пересжимает с нуля. Это паттерн Hermes Agent — предотвращает экспоненциальное
 * раздувание summary на каждом цикле (см. архитектура §Поведение при повторных сжатиях).
 *
 * @param conversationBlock — отформатированный блок старой части разговора
 *   ("User: ...\n\nAssistant: ...\n\n---\n\n..." — caller формирует).
 * @param previousSummary — summary предыдущей compaction-итерации (Phase 2)
 *   или `null` (Phase 1, первое сжатие).
 */
export function buildCompactionUserPrompt(
  conversationBlock: string,
  previousSummary: string | null,
): string {
  if (previousSummary) {
    return [
      "У тебя уже есть summary предыдущей части разговора. Разговор продолжился — появились новые сообщения, которые тоже пора сжать.",
      "",
      "**Задача:** обнови существующий summary, включив информацию из новой части. Не пересжимай всё с нуля — сохрани и развей накопленное.",
      "",
      "## Предыдущий summary",
      "",
      previousSummary,
      "",
      "## Новая часть разговора (которую нужно включить в summary)",
      "",
      conversationBlock,
    ].join("\n");
  }

  return [
    "Вот часть разговора, которую нужно сжать в 5-секционный summary:",
    "",
    conversationBlock,
  ].join("\n");
}
