async function seed() {
  console.log("🌱 Seeding agents...");

  try {
    // Clear existing agents
    console.log("  Clearing existing agents...");
    await db.delete(agent);

    // Insert new agents
    console.log("  Inserting agents...");
    for (const agentData of agents) {
      await db.insert(agent).values({
        slug: agentData.slug,
        type: agentData.type,
        name: agentData.name,
        icon: agentData.icon,
        description: agentData.description,
        systemPrompt: agentData.systemPrompt,
        greeting: agentData.greeting,
        defaultModel: agentData.defaultModel,
        toolAccess: agentData.toolAccess,
        capabilities: agentData.capabilities,
        sortOrder: agentData.sortOrder,
      });
      console.log(`    ✓ ${agentData.icon} ${agentData.name}`);
    }

    console.log(`\n✅ Seeded ${agents.length} agents successfully!`);
  } catch (error) {
    console.error("❌ Seed failed:", error);
    process.exit(1);
  }

  process.exit(0);
}

seed();
